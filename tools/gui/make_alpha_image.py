#!/usr/bin/env python
"""Turn a one-color PNG (the Offband mark) into an LVGL 8 alpha-only image.

The GUI draws it tinted with the theme's signal color (img_recolor), so
one 8-bit alpha mask serves every theme.

    python tools/gui/make_alpha_image.py <png> <size> <name> <out.c>

The mark is cropped to its drawn area, centered in a square, and scaled to
size x size. Source of record: the design handoff's assets/offband-mark.png.
"""
import sys

from PIL import Image


def main(png, size, name, out):
    im = Image.open(png).convert("RGBA")
    alpha = im.getchannel("A")
    box = alpha.getbbox()
    if box is None:
        sys.exit("empty image")
    alpha = alpha.crop(box)
    side = max(alpha.size)
    square = Image.new("L", (side, side), 0)
    square.paste(alpha, ((side - alpha.size[0]) // 2, (side - alpha.size[1]) // 2))
    square = square.resize((size, size), Image.LANCZOS)
    data = square.tobytes()

    rows = []
    for i in range(0, len(data), 16):
        rows.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    body = "\n".join(rows)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            f"// Generated by tools/gui/make_alpha_image.py from the Offband mark; do not edit.\n"
            f"// {size}x{size}, 8-bit alpha, drawn tinted with the theme's signal color.\n\n"
            f"#include <lvgl.h>\n\n"
            f"static const uint8_t {name}_map[] = {{\n{body}\n}};\n\n"
            f"const lv_img_dsc_t {name} = {{\n"
            f"    {{LV_IMG_CF_ALPHA_8BIT, 0, 0, {size}, {size}}},\n"
            f"    sizeof({name}_map),\n"
            f"    {name}_map,\n"
            f"}};\n"
        )


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4])
